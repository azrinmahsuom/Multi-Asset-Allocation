"""Write docs/evidence_review.md from the claim results. Every number in it comes from code."""

from importlib import import_module

import pandas as pd

from analysis.config import ROOT
from analysis.evidence import ClaimResult

CLAIM_MODULES = [
    "analysis.evidence.claim01_equity_premium",
    "analysis.evidence.claim02_rolling_20y",
    "analysis.evidence.claim03_mean_reversion",
    "analysis.evidence.claim04_horizon_mix",
    "analysis.evidence.claim05_stock_bond_correlation",
]

OUTPUT = ROOT / "docs" / "evidence_review.md"


def _table_markdown(df: pd.DataFrame) -> str:
    """Render a table with percentages for float columns that look like returns."""

    def fmt(value):
        if isinstance(value, float):
            if abs(value) < 1.5:
                return f"{value:.1%}"
            return str(int(value)) if value.is_integer() else f"{value:,.1f}"
        return str(value)

    header = "| " + " | ".join([df.index.name or "", *map(str, df.columns)]) + " |"
    rule = "|" + "---|" * (len(df.columns) + 1)
    rows = [
        "| " + " | ".join([str(idx), *(fmt(v) for v in row)]) + " |"
        for idx, row in zip(df.index, df.itertuples(index=False), strict=True)
    ]
    return "\n".join([header, rule, *rows])


def _section(result: ClaimResult) -> str:
    lines = [
        f"## Claim {result.number}: {result.claim}",
        "",
        f"**Verdict: {result.verdict}.** {result.headline}",
        "",
        f"**Data.** {result.data}",
        "",
        f"**Method.** {result.method}",
        "",
        "**Findings**",
        "",
        *[f"- {finding}" for finding in result.findings],
        "",
    ]
    for figure in result.figures:
        rel = figure.relative_to(ROOT).as_posix()
        lines += [f"![Claim {result.number}](../{rel})", ""]
    lines += ["**Caveats**", "", *[f"- {caveat}" for caveat in result.caveats], ""]
    for name, table in result.tables.items():
        lines += [
            "<details>",
            f"<summary>Table: {name.replace('_', ' ')}</summary>",
            "",
            _table_markdown(table),
            "",
            "</details>",
            "",
        ]
    return "\n".join(lines)


def run() -> list[ClaimResult]:
    results = [import_module(name).run() for name in CLAIM_MODULES]
    summary = _table_markdown(
        pd.DataFrame(
            {"Claim": [r.claim for r in results], "Verdict": [r.verdict for r in results]},
            index=pd.Index([r.number for r in results], name="#"),
        )
    )
    text = "\n".join(
        [
            "# Evidence review",
            "",
            "Generated by `uv run python -m analysis.pipeline evidence`; do not edit by hand. "
            "Verdicts follow fixed rules: a claim *holds* if true in every case tested, "
            "*partially holds* if true in more than half, and *fails* otherwise (see "
            "`analysis.evidence.verdict_from_share`).",
            "",
            summary,
            "",
            *[_section(r) for r in results],
        ]
    )
    OUTPUT.write_text(text)
    return results
