OUTPUT = ROOT / "docs" / "evidence_review.md"


# Columns holding ratios, statistics or other unitless numbers: shown as plain decimals.
PLAIN_NUMBER_KEYS = (
    "_bps",
    "orders",
    "sharpe",
    "sortino",
    "corr",
    "t_stat",
    "beta",
    "ratio",
    "rank",
    "slope",
    "p_value",
    "variance",
    "vr_",
    "iid_",
    "modified_z",
    "duration",
    "maturity",
    "ci_",
)


def _is_plain(column: str) -> bool:
    c = column.lower()
    return c.endswith("_t") or any(k in c for k in PLAIN_NUMBER_KEYS)


def _table_markdown(df: pd.DataFrame) -> str:
    """Render a table: returns and weights as percentages, ratios and statistics as decimals."""

    def fmt(value, column: str):
        if isinstance(value, float):
            if np.isnan(value):
                return "n/a"
            if _is_plain(column):
                return f"{value:.2f}"
            if abs(value) < 1.5:
                return f"{value:.1%}"
            return str(int(value)) if value.is_integer() else f"{value:,.1f}"
        return str(value)

    columns = [str(c) for c in df.columns]
    header = "| " + " | ".join([df.index.name or "", *columns]) + " |"
    rule = "|" + "---|" * (len(df.columns) + 1)
    rows = [
        "| "
        + " | ".join([str(idx), *(fmt(v, c) for v, c in zip(row, columns, strict=True))])
        + " |"
        for idx, row in zip(df.index, df.itertuples(index=False), strict=True)
    ]
    return "\n".join([header, rule, *rows])


def _section(result: ClaimResult) -> str:
    lines = [
        f"## Claim {result.number}: {result.claim}",
        "",
        f"**Verdict: {result.verdict}.** {result.headline}",
        "",
        f"**Data.** {result.data}",
        "",
        f"**Method.** {result.method}",
        "",
        "**Findings**",
        "",
        *[f"- {finding}" for finding in result.findings],
        "",
    ]
    for figure in result.figures:
        rel = figure.relative_to(ROOT).as_posix()
        lines += [f"![Claim {result.number}](../{rel})", ""]
    lines += ["**Caveats**", "", *[f"- {caveat}" for caveat in result.caveats], ""]
    if "JST" in result.data:
        lines += [f"*{JST_CREDIT} Applies to the JST-derived figures and tables above.*", ""]
    for name, table in result.tables.items():
        lines += [
            "<details>",
            f"<summary>Table: {name.replace('_', ' ')}</summary>",
            "",
            _table_markdown(table),
            "",
            "</details>",
            "",
        ]
    return "\n".join(lines)


def _sensitivity_section() -> str:
    table = sensitivity.run()
    n_changed = int(table["changes_verdict"].sum())
    shown = table.assign(default=table["default"].map({True: "yes", False: ""}))
    shown = shown.assign(changes_verdict=table["changes_verdict"].map({True: "YES", False: "no"}))
    return "\n".join(
        [
            "## Sensitivity of verdicts to window choices",
            "",
            "Window and horizon lengths with no cited source are rerun at alternatives either "
            f"side of the default. {n_changed} of {len(table)} alternatives change a verdict.",
            "",
            _table_markdown(shown.set_index("claim")),
            "",
            "The claim 5 burn-in alternatives give identical results because US CPI data start "
            "in 1947, so every burn-in ends before the February 1962 start of the return sample.",
            "",
        ]
    )


def run() -> list[ClaimResult]:
    results = [import_module(name).run() for name in CLAIM_MODULES]
    summary = _table_markdown(
        pd.DataFrame(
            {
                "Claim": [r.claim for r in results],
                "Verdict": [r.summary_label or r.verdict for r in results],
            },
            index=pd.Index([r.number for r in results], name="#"),
        )
    )
    text = "\n".join(
        [
            "# Evidence review",
            "",
            "Generated by `uv run python -m analysis.pipeline evidence`; do not edit by hand. "
            "Verdicts follow fixed rules: a claim *holds* if true in every case tested, "
            "*partially holds* if true in more than half, and *fails* otherwise (see "
            "`analysis.evidence.verdict_from_share`).",
            "",
            summary,
            "",
            *[_section(r) for r in results],
            _sensitivity_section(),
        ]
    )
    OUTPUT.write_text(text)
    return results
